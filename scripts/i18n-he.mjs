const tr = (s, rules) => { for (const [re, rep] of rules) if (re.test(s)) return s.replace(re, rep); return s; };
export const heString = (s) => (typeof s !== 'string' ? s : (EXACT[s] ?? tr(s, PATTERN)));
export const heTitle = (s) => (typeof s !== 'string' ? s : tr(s, TITLE));

export function localizeFinding(f) {
  if (f.source === 'manual') return f; // the agent writes those in the report language already
  const out = { ...f, title: heTitle(f.title) };
  for (const k of ['expected', 'actual', 'remediation']) if (out[k]) out[k] = heString(out[k]);
  if (out.steps) out.steps = out.steps.map(heString);
  if (out.evidence?.details) out.evidence = { ...out.evidence, details: heString(out.evidence.details) };
  return out;
}
